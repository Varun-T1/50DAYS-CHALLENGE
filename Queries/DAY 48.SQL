1.Question: Find total business revenue.
SELECT SUM(payment_amount) AS total_revenue
FROM cleaned_payments;

2.Question: Find daily revenue.
SELECT payment_date,
SUM(payment_amount) AS daily_revenue
FROM cleaned_payments
GROUP BY payment_date
ORDER BY payment_date;

3.Question: Find monthly revenue trend.
SELECT MONTHNAME(payment_date)AS month_name,
MONTH(payment_date)AS month_number,
SUM(payment_amount) AS monthly_revenue
FROM cleaned_payments
GROUP BY MONTHNAME(payment_date),MONTH(payment_date)
ORDER BY month_number;

4.Question: Find revenue generated by each product.
SELECT p.product_id,
p.product_name,
SUM(od.quantity * p.price) AS total_revenue
FROM cleaned_products p
JOIN cleaned_order_details od
ON p.product_id = od.product_id
GROUP BY p.product_id, p.product_name
ORDER BY total_revenue DESC;

5.Question: Find customer-wise revenue.
SELECT c.customer_id,
c.customer_name,
SUM(p.payment_amount) AS customer_revenue
FROM cleaned_customers c
JOIN cleaned_orders o
ON c.customer_id = o.customer_id
JOIN cleaned_payments p
ON o.order_id = p.order_id
GROUP BY c.customer_id, c.customer_name
ORDER BY customer_revenue DESC;

6.Question: Find category-wise revenue.
SELECT p.category,
SUM(od.quantity * p.price) AS category_revenue
FROM cleaned_products p
JOIN cleaned_order_details od
ON p.product_id = od.product_id
GROUP BY p.category
ORDER BY category_revenue DESC;

7.Question: Find days generating highest revenue.
SELECT payment_date,
SUM(payment_amount) AS daily_revenue
FROM cleaned_payments
GROUP BY payment_date
ORDER BY daily_revenue DESC;